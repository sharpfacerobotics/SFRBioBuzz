import java.io.File;

import java.util.ArrayList;

import static com.pedropathing.api.Paths.curve;
import static com.pedropathing.api.Paths.line;

/**
 * Shared plumbing for every auto. A specific auto only has to:
 * <ol>
 *   <li>give its start pose ({@link #startPose()}), written for RED, and</li>
 *   <li>list its steps in {@link #buildRoutine()} with drive / driveIntaking / shoot / pause.</li>
 * </ol>
 * Blue is generated by rotating every red pose 180 degrees about the field centre (the
 * BIOBUZZ field is rotationally symmetric, not mirrored), so each auto has one set of numbers.
 *
 * <p>BIOBUZZ AUTO rules built in: every pose is checked to stay on our half (G402 - init
 * telemetry warns if not), we always aim at whichever of our cells is facing up (G417), and
 * PoseStorage is saved every loop for TeleOp.</p>
 *
 * <p>All paths are built during init. The loop allocates nothing.</p>
 *
 * <p>Setup: place the robot on its start pose with the turret facing straight forward
 * (the turret zero is taken from that position, so it doesn't spend auto time homing).</p>
 *
 * <p>Init menu on gamepad1 (so the drive team can adjust to their partner without code):
 * dpad up/down = start delay +/- 0.5 s, dpad left/right = preload count.</p>
 */
public abstract class AutoBase extends LinearOpMode {

    protected abstract Alliance alliance();

    /** Starting pose for RED (touching our wall, not in the LOADING ZONE - G304). */
    protected abstract Pose startPose();

    /** Call drive/driveIntaking/shoot/pause in order. Poses are RED; they get rotated for blue. */
    protected abstract void buildRoutine();

    // ------------------------------------------------------------------ routine building

    private enum Action { DRIVE, DRIVE_INTAKING, SHOOT, PAUSE }

    private static class Step {
        final Action action;
        final Path path;
        final double seconds;
        final String label;

        Step(Action action, Path path, double seconds, String label) {
            this.action = action;
            this.path = path;
            this.seconds = seconds;
            this.label = label;
        }
    }

    private final ArrayList<Step> steps = new ArrayList<>();
    private Pose lastPose;
    private int sideViolations = 0;

    /** Straight line from wherever the last step ended, heading blends to the target's. */
    protected void drive(String label, Pose redTarget) {
        Pose target = field(redTarget);
        checkSide(target);
        steps.add(new Step(Action.DRIVE, line(lastPose, target).linear(lastPose, target), 0, label));
        lastPose = target;
    }

    /** Bezier curve through a red control point. */
    protected void drive(String label, Pose redControl, Pose redTarget) {
        Pose target = field(redTarget);
        Pose control = field(redControl);
        checkSide(target);
        checkSide(control);
        steps.add(new Step(Action.DRIVE, curve(lastPose, control, target).linear(lastPose, target), 0, label));
        lastPose = target;
    }

    /** Drive with the intake running, then sit for a moment to finish swallowing. */
    protected void driveIntaking(String label, Pose redTarget) {
        Pose target = field(redTarget);
        checkSide(target);
        steps.add(new Step(Action.DRIVE_INTAKING, line(lastPose, target).constant(target), 0, label));
        lastPose = target;
    }

    /** Hold position and fire until storage is empty (or AUTO_SHOOT_TIMEOUT). */
    protected void shoot(String label) {
        steps.add(new Step(Action.SHOOT, null, 0, label));
    }

    protected void pause(String label, double seconds) {
        steps.add(new Step(Action.PAUSE, null, seconds, label));
    }

    /** Red pose -> this alliance's pose. Blue is the 180 degree rotation about field centre. */
    protected Pose field(Pose red) {
        if (alliance() == Alliance.RED) {
            return red;
        }
        return new Pose(FieldGeometry.rotateX(red.x()), FieldGeometry.rotateY(red.y()),
                FieldGeometry.rotateHeading(red.heading()));
    }

    /** G402: crossing to the opponent's half in AUTO risks a MAJOR FOUL. */
    private void checkSide(Pose pose) {
        if (!FieldGeometry.onOwnSide(alliance() == Alliance.RED, pose.x())) {
            sideViolations++;
        }
    }

    /** Builds every path for this alliance (no hardware needed). Returns the start pose. */
    Pose prepareRoutine() {
        Pose start = field(startPose());
        lastPose = start;
        steps.clear();
        sideViolations = 0;
        checkSide(start);
        buildRoutine();
        return start;
    }

    int getStepCount() {
        return steps.size();
    }

    /** Number of path points on the opponent's half (should be 0). */
    int getSideViolations() {
        return sideViolations;
    }

    /** Pose where the routine ends. */
    Pose getEndPose() {
        return lastPose;
    }

    /** Shorthand: red pose with heading in degrees. */
    protected static Pose pose(double x, double y, double headingDeg) {
        return new Pose(x, y, Math.toRadians(headingDeg));
    }

    // ------------------------------------------------------------------ running

    protected final RobotHardware robot = new RobotHardware();
    protected final Intake intake = new Intake(robot);
    protected final Storage storage = new Storage(robot);
    protected final ShooterConfig shooterConfig = new ShooterConfig(robot);
    protected final Launcher launcher = new Launcher(robot);
    protected final Turret turret = new Turret(robot);
    protected final Trigger trigger = new Trigger(robot);
    protected final HiveVision hiveVision = new HiveVision(robot);

    private final ElapsedTime stepTimer = new ElapsedTime();
    private final ElapsedTime voltageTimer = new ElapsedTime();
    private final ElapsedTime matchTimer = new ElapsedTime();
    private final ElapsedTime carryTimer = new ElapsedTime();
    private final ElapsedTime rejectTimer = new ElapsedTime();
    private boolean rejecting = false;
    private int shotsFired = 0;
    private int stepIndex = 0;
    private boolean pathDone = false;
    private boolean routineStarted = false;
    private boolean carrying = false;
    private double startDelay = 0;
    private int preloadCount = RobotConfig.AUTO_PRELOAD_COUNT;

    @Override
    public void runOpMode() {
        telemetry = new JoinedTelemetry(PanelsTelemetry.INSTANCE.getFtcTelemetry(), telemetry);
        robot.init(hardwareMap);
        FieldDrawing fieldDrawing = new FieldDrawing();
        MatchLogger log = new MatchLogger(new File(AppUtil.ROBOT_DATA_DIR, "matchlogs"),
                "auto_" + getClass().getSimpleName(), "x", "y", "heading", "step", "storage",
                "flyTarget", "flyVel", "flyReady", "turretOnTarget", "shooting", "shotsTotal");
        boolean red = alliance() == Alliance.RED;
        double goalX = FieldGeometry.cellX(red);
        HiveTracker hive = new HiveTracker(FieldGeometry.startingUpCell(red));
        Element opponentNectar = RobotConfig.opponentNectar(alliance());

        Pose start = prepareRoutine();

        robot.follower.setPose(start);
        turret.forceZeroHere();
        trigger.stopFiring();
        hiveVision.activate();

        while (opModeInInit()) {
            if (gamepad1.dpadUpWasPressed()) {
                startDelay = Math.min(startDelay + 0.5, RobotConfig.AUTO_MAX_START_DELAY);
            }
            if (gamepad1.dpadDownWasPressed()) {
                startDelay = Math.max(startDelay - 0.5, 0);
            }
            if (gamepad1.dpadRightWasPressed()) {
                preloadCount = Math.min(preloadCount + 1, RobotConfig.STORAGE_CAPACITY);
            }
            if (gamepad1.dpadLeftWasPressed()) {
                preloadCount = Math.max(preloadCount - 1, 0);
            }
            telemetry.addData("Auto", "%s  %s", getClass().getSimpleName(), alliance());
            telemetry.addData("Steps", steps.size());
            telemetry.addData("Start delay (dpad up/down)", "%.1f s", startDelay);
            telemetry.addData("Preloads (dpad left/right)", preloadCount);
            telemetry.addLine("Turret must be facing straight forward!");
            if (sideViolations > 0) {
                telemetry.addData("⚠ G402", "%d path points on the OPPONENT's half - fix the poses", sideViolations);
            }
            telemetry.update();
        }
        if (isStopRequested()) {
            return;
        }

        storage.preload(preloadCount, Element.POLLEN); // G304: 4 POLLEN pre-loads
        turret.restartTimer();
        matchTimer.reset();
        robot.follower.hold(start);
        double voltage = robot.getVoltage();

        while (opModeIsActive()) {
            robot.clearBulkCache();
            robot.follower.update();
            Pose pose = robot.follower.pose();
            Velocity velocity = robot.follower.velocity();
            PoseStorage.save(pose); // every loop, in case auto gets cut off at 30 s
            PoseStorage.saveHive(hive.getUpCell(), hive.getWeight());

            if (voltageTimer.seconds() > 0.25) {
                voltageTimer.reset();
                voltage = robot.getVoltage();
            }

            // Wait out the start delay (flywheel + turret still spin up meanwhile).
            if (!routineStarted && matchTimer.seconds() >= startDelay) {
                routineStarted = true;
                startStep(0);
            }

            Step step = routineStarted && stepIndex < steps.size() ? steps.get(stepIndex) : null;
            boolean shooting = step != null && step.action == Action.SHOOT;
            // Keep the rollers going briefly after a pickup so the last element gets all the way in.
            boolean intaking = (step != null && step.action == Action.DRIVE_INTAKING)
                    || (carrying && carryTimer.seconds() < RobotConfig.AUTO_INTAKE_CARRY);

            // Aim at whichever of our cells is up; a tip (ours or our partner's) flips it.
            FieldGeometry.Cell upCell = hive.getUpCell();
            hiveVision.update(FieldGeometry.tagBase(red, upCell), FieldGeometry.tagBase(red, FieldGeometry.other(upCell)),
                    pose.heading(), velocity.omega);
            hive.update(hiveVision.hasTarget(), hiveVision.seesOtherCell(), matchTimer.seconds());
            double goalY = FieldGeometry.cellY(hive.getUpCell());

            // Spit out opponent NECTAR (G408) or a 5th element (G407).
            if (rejecting && rejectTimer.seconds() > RobotConfig.REJECT_TIME) {
                rejecting = false;
            }
            storage.update(intaking && !rejecting, rejecting, opponentNectar);
            if (storage.shouldReject()) {
                rejecting = true;
                rejectTimer.reset();
            }
            intake.update(intaking && !rejecting, rejecting, storage.isFull());

            shooterConfig.calculateShootingConfig(pose.x(), pose.y(), pose.heading(), velocity.vx, velocity.vy,
                    goalX, goalY, hiveVision.getAverageTa());
            turret.updateTurret(shooterConfig.getTurretAngle(), velocity.omega);

            // Keep the flywheel at speed all auto so shots never wait on spin-up.
            Element next = storage.peekNext();
            launcher.update(shooterConfig.getTargetVelocity(), shooterConfig.getHoodAngle(next), next, voltage);

            if (shooting) {
                // Hold fire while the hive swings after a tip - the 3rd pre-load tips it and
                // the 4th must go into the OTHER cell once it has settled.
                trigger.fire(launcher.isReady(), turret.isOnTarget() && !hive.isSettling(matchTimer.seconds()));
                if (launcher.shotDetected()) {
                    hive.recordShot(next != null && next.isNectar(), matchTimer.seconds());
                    storage.removeNext();
                    shotsFired++; // running total so the 20 Hz log can't miss a shot
                }
            } else {
                trigger.stopFiring();
            }

            if (step != null && isStepDone(step)) {
                if (step.action == Action.SHOOT) {
                    storage.clear(); // whatever the count says, we fired for the full window
                }
                if (step.action == Action.DRIVE_INTAKING) {
                    carrying = true;
                    carryTimer.reset();
                }
                startStep(stepIndex + 1);
            }

            if (log.shouldLog(matchTimer.seconds())) {
                log.value(pose.x()).value(pose.y()).value(pose.heading()).value(stepIndex)
                        .value(storage.count()).value(launcher.getTargetVelocity()).value(launcher.getCurrVelocity())
                        .value(launcher.isReady()).value(turret.isOnTarget()).value(shooting).value(shotsFired).endRow();
            }

            fieldDrawing.draw(pose.x(), pose.y(), pose.heading(), shooterConfig.getFieldAimHeading(),
                    shooterConfig.getDistanceToGoal(), goalX, goalY);

            telemetry.addData("Step", "%d/%d %s", Math.min(stepIndex + 1, steps.size()), steps.size(),
                    !routineStarted ? "start delay" : step == null ? "done" : step.label);
            telemetry.addData("Pose", "x %.1f  y %.1f  h %.1f°", pose.x(), pose.y(), Math.toDegrees(pose.heading()));
            telemetry.addData("Storage", storage.count());
            telemetry.addData("Hive", "aiming at %s cell, tips seen %d", hive.getUpCell(), hive.getTips());
            telemetry.addData("Flywheel", "%.0f / %.0f", launcher.getCurrVelocity(), launcher.getTargetVelocity());
            telemetry.update();
        }

        PoseStorage.save(robot.follower.pose());
        log.close();
        trigger.stopFiring();
        intake.stop();
        launcher.stop();
        turret.stop();
        robot.follower.stop();
    }

    private void startStep(int index) {
        stepIndex = index;
        stepTimer.reset();
        pathDone = false;
        if (index >= steps.size()) {
            robot.follower.hold(robot.follower.pose());
            return;
        }
        Step step = steps.get(index);
        if (step.path != null) {
            robot.follower.follow(step.path);
        } else {
            robot.follower.hold(robot.follower.pose()); // stay put while shooting/pausing
        }
    }

    private boolean isStepDone(Step step) {
        double t = stepTimer.seconds();
        switch (step.action) {
            case DRIVE:
                return !robot.follower.isBusy() || t > RobotConfig.AUTO_PATH_TIMEOUT;
            case DRIVE_INTAKING:
                if (!pathDone && (!robot.follower.isBusy() || t > RobotConfig.AUTO_PATH_TIMEOUT)) {
                    pathDone = true;
                    stepTimer.reset(); // now time the dwell
                    return false;
                }
                return pathDone && (t > RobotConfig.AUTO_INTAKE_DWELL || storage.isFull());
            case SHOOT:
                return storage.isEmpty() || t > RobotConfig.AUTO_SHOOT_TIMEOUT + HiveTracker.SETTLE_TIME;
            case PAUSE:
            default:
                return t > step.seconds;
        }
    }
}
